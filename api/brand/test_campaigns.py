EDITABLE = (
    "title",
    "intent",
    "persona",
    "goal",
    "behaviour",
    "facts",
    "criteria",
    "forbidden",
    "expected_end_node",
    "expected_variables",
    "expected_tools",
    "tool_hints",
    "levels",
    "speed",
    "voice",
    "caller_number",
    "enabled",
)


def update_scenario(campaign: dict, scenario_id: str, changes: dict) -> dict:
    scenario = next((s for s in campaign["scenarios"] if s["id"] == scenario_id), None)
    if scenario is None:
        raise LookupError("scenario not found")
    for key in EDITABLE:
        if key not in changes:
            continue
        value = changes[key]
        if key == "levels":
            value = {
                k: max(1, min(5, int(v)))
                for k, v in (value or {}).items()
                if k in DIMENSIONS
            }
        elif key == "speed":
            value = round(max(SPEED_LIMITS[0], min(SPEED_LIMITS[1], float(value))), 2)
        elif key in ("criteria", "forbidden", "expected_tools"):
            value = [str(v) for v in value or [] if str(v).strip()]
        elif key in ("facts", "expected_variables"):
            value = {str(k): str(v) for k, v in (value or {}).items() if str(k).strip()}
        elif key == "voice" and value is not None:
            value = (_clean_voices([value]) or [None])[0]
        elif key == "enabled":
            value = bool(value)
        scenario[key] = value
    scenario["edited_at"] = _now()
    return scenario


def duplicate_scenario(campaign: dict, scenario_id: str, levels: dict | None) -> dict:
    """A variant: same request, other caller levels (edited afterwards)."""
    import copy

    source = next((s for s in campaign["scenarios"] if s["id"] == scenario_id), None)
    if source is None:
        raise LookupError("scenario not found")
    if len(campaign["scenarios"]) >= MAX_SCENARIOS:
        raise CampaignError(f"a campaign holds at most {MAX_SCENARIOS} scenarios")
    variant = copy.deepcopy(source)
    variant.update(
        id=uuid.uuid4().hex[:10],
        variant_of=source.get("variant_of") or source["id"],
        title=f"{source['title']} (variant)",
        edited_at=_now(),
    )
    if levels:
        update_scenario({"scenarios": [variant]}, variant["id"], {"levels": levels})
    campaign["scenarios"].insert(campaign["scenarios"].index(source) + 1, variant)
    return variant
