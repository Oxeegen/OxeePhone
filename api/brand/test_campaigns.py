async def generate(organization_id: int, campaign_id: str) -> None:
    """Background: write the campaign's scenarios, batch by batch."""
    from api.brand.analysis import resolve_analysis_model
    from api.brand.llm import chat_json

    campaign = await get(organization_id, campaign_id)
    if campaign is None:
        return
    try:
        model = await resolve_analysis_model(organization_id)
        if not model:
            raise CampaignError("no analysis model configured (Models › Analysis)")
        workflow = await db_client.get_workflow(
            campaign["workflow_id"], organization_id=organization_id
        )
        if workflow is None:
            raise CampaignError("agent not found")
        definition = await db_client.get_draft_version(workflow.id) or (
            await brand_db.get_workflow_version(
                workflow.id, workflow.released_definition_id
            )
        )
        brief = agent_brief(
            definition.workflow_json or {}, definition.workflow_configurations or {}
        )
        brief["tools"] = await _tool_names(organization_id, brief.pop("tool_uuids"))
        settings = await get_settings(organization_id)
        missing = campaign["count"] - len(campaign["scenarios"])
        seed = campaign["seed"] + len(campaign["scenarios"])
        levels = draw_levels(campaign["ranges"], missing, seed)
        speeds = draw_speeds(campaign["speed"], missing, seed)
        slots = [{"levels": lv, "speed": sp} for lv, sp in zip(levels, speeds)]
        _assign_pools(slots, settings, seed)
        campaign["generation"] = {
            "done": len(campaign["scenarios"]),
            "total": campaign["count"],
            "error": None,
        }
        for start in range(0, len(slots), GENERATION_BATCH):
            batch = slots[start : start + GENERATION_BATCH]
            payload = {
                "today": datetime.now(UTC).strftime("%A %d %B %Y"),
                "agent": {"name": workflow.name, **brief},
                "instructions": campaign.get("instructions"),
                "already_written": [
                    f"{s['title']} ({s['intent']})" for s in campaign["scenarios"]
                ][-60:],
                "slots": [
                    {
                        "slot": i + 1,
                        "levels": s["levels"],
                        "voice_gender": (s.get("voice") or {}).get("gender", "unknown"),
                    }
                    for i, s in enumerate(batch)
                ],
            }
            result = await chat_json(
                model,
                GENERATE_PROMPT.replace("{language}", campaign["language"]),
                payload,
                max_tokens=8000,
                temperature=0.7,
                timeout=240.0,
            )
            by_slot = {
                int(r.get("slot", 0)): r
                for r in result.get("scenarios") or []
                if isinstance(r, dict)
            }
            for i, slot in enumerate(batch):
                raw = by_slot.get(i + 1)
                if raw:
                    campaign["scenarios"].append(_scenario_from(raw, slot))
            campaign["generation"]["done"] = len(campaign["scenarios"])
            await save(organization_id, campaign)
        campaign["status"] = "ready"
        if len(campaign["scenarios"]) < campaign["count"]:
            campaign["generation"]["error"] = (
                f"the model wrote {len(campaign['scenarios'])} scenarios out of "
                f"{campaign['count']}"
            )
    except Exception as e:
        logger.warning(f"Test campaign {campaign_id}: generation failed: {e}")
        campaign["status"] = "ready" if campaign["scenarios"] else "failed"
        campaign["generation"] = {**(campaign.get("generation") or {}), "error": str(e)}
    await save(organization_id, campaign)


