"""Test campaigns: scenarios played against an agent by a simulated caller.

A campaign targets one agent and holds scenarios generated by the analysis
model from the agent's graph and from the caller settings (every setting is a
min / max range, see DIMENSIONS). Each scenario is one caller: a persona with
an identity, a goal, the facts it can give, success criteria, a voice and a
caller number from the organization's pools. Campaigns are replayed as
executions (see test_runs.py) on a version of the agent; two executions are
compared to see what a draft changes.

Storage (organization configurations, no migration):
    OXEE_TEST_SETTINGS          telephony + pools of the organization
    OXEE_TESTCAMP:<id>          one campaign and its scenarios
"""

