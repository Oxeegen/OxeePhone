def agent_brief(workflow_json: dict, configurations: dict) -> dict:
    """The agent as the generator and the judge see it."""
    from api.brand.fixes import agent_outline

    outline = agent_outline(workflow_json or {}, configurations or {})
    variables, tools = [], set()
    for n in (workflow_json or {}).get("nodes") or []:
        data = n.get("data") or {}
        for v in data.get("extraction_variables") or []:
            if isinstance(v, dict) and v.get("name"):
                variables.append(
                    {
                        "node": data.get("name"),
                        "name": v.get("name"),
                        "type": v.get("type"),
                        "hint": v.get("prompt") or v.get("description"),
                    }
                )
        tools.update(data.get("tool_uuids") or [])
    outline.pop("settings", None)
    return {
        **outline,
        "variables": variables,
        "tool_uuids": sorted(tools),
        "call_outcomes": [
            d.get("name") or d.get("code")
            for d in (configurations or {}).get("call_dispositions") or []
            if isinstance(d, dict)
        ],
    }


async def _tool_names(organization_id: int, uuids: list[str]) -> list[dict]:
    if not uuids:
        return []
    try:
        tools = await db_client.get_tools_by_uuids(uuids, organization_id)
    except Exception:
        return []
    return [
        {
            "name": getattr(t, "name", None),
            "description": (getattr(t, "description", None) or "")[:300],
        }
        for t in tools or []
    ]


def _assign_pools(scenarios: list[dict], settings: dict, seed: int) -> None:
    """Voice and caller number per scenario, without repeats while possible."""
    rng = random.Random(seed + 2)
    voices = list(settings.get("voices") or [])
    numbers = list(settings.get("caller_numbers") or [])
    rng.shuffle(voices)
    rng.shuffle(numbers)
    for i, s in enumerate(scenarios):
        if voices and not s.get("voice"):
            s["voice"] = voices[i % len(voices)]
        if numbers and not s.get("caller_number"):
            s["caller_number"] = numbers[i % len(numbers)]


