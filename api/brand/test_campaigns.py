SPEED_LIMITS = (0.7, 1.6)
DEFAULT_RANGES = {
    "vocabulary": [1, 3],
    "mood": [1, 3],
    "clarity": [1, 3],
    "complexity": [1, 3],
    "depth": [1, 3],
    "impatience": [1, 2],
    "dictation": [1, 3],
    "traps": [1, 1],
}
DEFAULT_SPEED = [0.95, 1.15]
TOOL_MODES = ("simulated", "real", "real_with_header")


class CampaignError(ValueError):
    pass


def _now() -> str:
    return datetime.now(UTC).isoformat()


def normalize_ranges(ranges: dict | None) -> dict[str, list[int]]:
    out = {}
    for key, default in DEFAULT_RANGES.items():
        raw = (ranges or {}).get(key, default)
        try:
            lo, hi = int(raw[0]), int(raw[1])
        except (TypeError, ValueError, IndexError) as e:
            raise CampaignError(f"{key}: expected [min, max]") from e
        lo, hi = max(1, min(5, lo)), max(1, min(5, hi))
        out[key] = [min(lo, hi), max(lo, hi)]
    return out


def normalize_speed(speed: list | None) -> list[float]:
    try:
        lo, hi = float((speed or DEFAULT_SPEED)[0]), float((speed or DEFAULT_SPEED)[1])
    except (TypeError, ValueError, IndexError) as e:
        raise CampaignError("speed: expected [min, max]") from e
    lo = max(SPEED_LIMITS[0], min(SPEED_LIMITS[1], lo))
    hi = max(SPEED_LIMITS[0], min(SPEED_LIMITS[1], hi))
    return [round(min(lo, hi), 2), round(max(lo, hi), 2)]


def draw_levels(ranges: dict[str, list[int]], count: int, seed: int) -> list[dict]:
    """Levels for ``count`` scenarios: every value of every range is used as
    evenly as possible (one shuffled cycle per dimension)."""
    rng = random.Random(seed)
    columns = {}
    for key, (lo, hi) in ranges.items():
        values = list(range(lo, hi + 1))
        column: list[int] = []
        while len(column) < count:
            cycle = values[:]
            rng.shuffle(cycle)
            column += cycle
        columns[key] = column[:count]
    return [{key: columns[key][i] for key in ranges} for i in range(count)]


def draw_speeds(speed: list[float], count: int, seed: int) -> list[float]:
    rng = random.Random(seed + 1)
    lo, hi = speed
    if count <= 1 or lo == hi:
        return [round(lo, 2)] * count
    step = (hi - lo) / (count - 1)
    values = [round(lo + i * step, 2) for i in range(count)]
    rng.shuffle(values)
    return values


# --- Organization settings --------------------------------------------------------


def default_settings() -> dict:
    return {
        "tester_telephony_configuration_id": None,
        "test_inbound_number": None,
        "caller_numbers": [],
        "voices": [],
        "concurrency": 2,
        "tester_workflow_id": None,
    }


async def get_settings(organization_id: int) -> dict:
    row = await db_client.get_configuration(organization_id, SETTINGS_KEY)
    return {**default_settings(), **(dict(row.value) if row and row.value else {})}


def _clean_numbers(numbers: list) -> list[str]:
    seen, out = set(), []
    for n in numbers or []:
        n = str(n or "").strip()
        if n and n not in seen and len(n) <= 40:
            seen.add(n)
            out.append(n)
    return out[:500]


def _clean_voices(voices: list) -> list[dict]:
    seen, out = set(), []
    for v in voices or []:
        if isinstance(v, str):
            v = {"id": v}
        vid = str((v or {}).get("id") or "").strip()
        if not vid or vid in seen:
            continue
        seen.add(vid)
        gender = str(v.get("gender") or "").lower()
        out.append(
            {
                "id": vid,
                "gender": gender if gender in ("female", "male") else "unknown",
                "label": str(v.get("label") or "").strip()[:60] or None,
            }
        )
    return out[:300]


async def save_settings(organization_id: int, changes: dict) -> dict:
    settings = await get_settings(organization_id)
    if "caller_numbers" in changes:
        settings["caller_numbers"] = _clean_numbers(changes["caller_numbers"])
    if "voices" in changes:
        settings["voices"] = _clean_voices(changes["voices"])
    if "tester_telephony_configuration_id" in changes:
        value = changes["tester_telephony_configuration_id"]
        settings["tester_telephony_configuration_id"] = int(value) if value else None
    if "test_inbound_number" in changes:
        settings["test_inbound_number"] = (
            str(changes["test_inbound_number"] or "").strip() or None
        )
    if "concurrency" in changes:
        settings["concurrency"] = max(1, min(10, int(changes["concurrency"] or 1)))
    await db_client.upsert_configuration(organization_id, SETTINGS_KEY, settings)
    return settings


